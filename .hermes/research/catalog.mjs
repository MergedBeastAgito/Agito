/**
 * Catalogue the captured conversations.
 *
 * Scans the research directory for record-shaped Markdown, reads the frontmatter
 * it finds there, and writes two artefacts beside them: `index.json` for a
 * program, and `Index.md` for a reader. Nothing is inferred from the filename -
 * the frontmatter is the source of truth, so a document without one is reported
 * rather than guessed at.
 *
 *   node catalog.mjs [<research-dir>]
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const Directory = process.argv[2] ?? join(process.cwd(), ".hermes", "research");

const Records = [];
const Problems = [];

for (const Entry of readdirSync(Directory).sort()) {
	if (!Entry.endsWith(".md") || Entry === "Index.md") continue;
	const Path = join(Directory, Entry);
	const Text = readFileSync(Path, "utf8");

	if (!Text.startsWith("---\n")) {
		Problems.push(`${Entry}: no frontmatter, so it is not catalogued`);
		continue;
	}
	const End = Text.indexOf("\n---\n", 3);
	if (End === -1) {
		Problems.push(`${Entry}: frontmatter is never closed`);
		continue;
	}

	const Fields = {};
	for (const Line of Text.slice(4, End).split("\n")) {
		const At = Line.indexOf(":");
		if (At === -1) continue;
		const Key = Line.slice(0, At).trim();
		let Value = Line.slice(At + 1).trim();
		if (Value.startsWith('"') && Value.endsWith('"')) Value = JSON.parse(Value);
		Fields[Key] = Value;
	}

	const Body = Text.slice(End + 5);
	const Headings = [...Body.matchAll(/^## (.+)$/gm)].map((Match) => Match[1].trim());

	Records.push({
		file: Entry,
		thread: Fields["thread"] ?? null,
		title: Fields["title"] ?? null,
		project: Fields["project"] ?? null,
		kind: Fields["kind"] ?? null,
		status: Fields["status"] ?? null,
		date: Fields["date"] ?? null,
		captured: Fields["captured"] ?? null,
		source: Fields["source"] ?? null,
		segments: Number(Fields["segments"] ?? 0),
		steps: Number(Fields["steps"] ?? 0),
		sources: Number(Fields["sources"] ?? 0),
		characters: Body.trim().length,
		sections: Headings,
	});
}

const Total = Records.reduce((Sum, Record) => Sum + Record.characters, 0);

writeFileSync(join(Directory, "index.json"), JSON.stringify({ captured: new Date().toISOString(), total: Records.length, characters: Total, records: Records }, null, "\t") + "\n");

const Rows = Records.map(
	(Record) =>
		`| [\`${Record.thread ?? "?"}\`](${Record.file}) | ${Record.title ?? "-"} | ${Record.project ?? "-"} | ${Record.characters.toLocaleString()} | ${Record.steps} | ${Record.sources} |`,
);

writeFileSync(
	join(Directory, "Index.md"),
	[
		"# Captured conversations",
		"",
		"One record per research thread, shaped like a decision record: frontmatter, a metadata table, the",
		"transcript, the step trace and the cited sources. The thread id is the filename, because a title",
		"changes when a follow-up is asked.",
		"",
		`${Records.length} record(s), ${Total.toLocaleString()} characters. Generated by \`catalog.mjs\`; do not edit by hand.`,
		"",
		"| Thread | Title | Project | Characters | Steps | Sources |",
		"| --- | --- | --- | --- | --- | --- |",
		...Rows,
		"",
		...(Problems.length > 0 ? ["## Not catalogued", "", ...Problems.map((Problem) => `- ${Problem}`), ""] : []),
	].join("\n"),
);

console.log(`records: ${Records.length}  characters: ${Total}`);
for (const Problem of Problems) console.log(`skip: ${Problem}`);
